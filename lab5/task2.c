#include <stdio.h>

int main() {
    int N = 10;
    // 1-2. Массивы для реальной и мнимой частей в диапазоне [-32768..32767]
    double re[10] = {-1234.0, 5000.0, -15000.0, 800.0, -32000.0, 120.0, -900.0, 23000.0, -450.0, 7000.0};
    double im[10] = {-3000.0, -1200.0, 8000.0, -400.0, 15000.0, -600.0, 700.0, -11000.0, 200.0, -5000.0};
    
    double energy = 0;
    double max_re = re[0];
    int max_re_idx = 0;

    // 3. Вывод отсчётов в требуемом формате
    for (int k = 0; k < N; k++) {
        printf("s[%d] = %.1f + j*(%.1f)\n", k, re[k], im[k]);
        
        // 4. Считаем энергию сигнала: сумма квадратов частей
        energy += (re[k] * re[k]) + (im[k] * im[k]);

        // 5. Поиск максимума реальной части
        if (re[k] > max_re) {
            max_re = re[k];
            max_re_idx = k;
        }
    }

    printf("\nЭнергия сигнала E = %.1f\n", energy);
    printf("Максимальный элемент среди реальной части: re[%d] = %.1f\n", max_re_idx, max_re);

    return 0;
}
